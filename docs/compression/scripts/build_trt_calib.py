"""Build INT8 TRT engines from FP32 ONNX via TRT NATIVE INT8 calibration.

This is the standard TRT INT8 path (IInt8EntropyCalibrator2), NOT the
onnxruntime-QDQ route (whose INT32-bias DequantizeLinear TRT cannot parse).
Calibration data = the SAME distribution validated accuracy-free on CPU
(quantize_int8.py): real Push-T obs for the encoder, (randn sample, uniform
timestep, encoded global_cond) for the unet — generated by gen_calib_data.py.

Device memory for the calibrator uses ctypes + libcudart directly, because the
Orin has no torch/pycuda/cuda-python.

Example (on dog, /home/vision/homebot_wm):
  python3 build_trt_calib.py --onnx_dir onnx_fp32 --calib_dir calib_data \
      --out_dir engines --which both
"""
import argparse
import ctypes
import pathlib

import numpy as np
import tensorrt as trt

TRT_LOGGER = trt.Logger(trt.Logger.WARNING)
cudart = ctypes.CDLL("libcudart.so")


def _ck(err, fn):
    if err != 0:
        raise RuntimeError(f"{fn} failed: cudaError={err}")


def cuda_malloc(nbytes):
    ptr = ctypes.c_void_p()
    _ck(cudart.cudaMalloc(ctypes.byref(ptr), ctypes.c_size_t(nbytes)), "cudaMalloc")
    return ptr.value  # int device address; int(c_void_p) misfires via buffer protocol


def cuda_memcpy_h2d(dst_addr, src_np):
    src = np.ascontiguousarray(src_np)
    _ck(cudart.cudaMemcpy(ctypes.c_void_p(dst_addr), src.ctypes.data_as(ctypes.c_void_p),
                          ctypes.c_size_t(src.nbytes), 1), "cudaMemcpy")  # 1=HostToDevice


class Calibrator(trt.IInt8EntropyCalibrator2):
    """Feeds calibration batches; device buffers allocated lazily on first use
    (CUDA context is only active once TRT starts calibrating)."""

    def __init__(self, inputs, batch_size, cache_file):
        super().__init__()
        self.inputs = inputs          # dict name -> (N, ...) np array
        self.batch_size = batch_size
        self.n = len(next(iter(inputs.values())))
        self.idx = 0
        self.cache_file = pathlib.Path(cache_file)
        self.dptrs = None

    def get_batch_size(self):
        return self.batch_size

    def get_batch(self, names):
        if self.idx >= self.n:
            return None
        end = min(self.idx + self.batch_size, self.n)
        if self.dptrs is None:
            self.dptrs = {nm: cuda_malloc(np.ascontiguousarray(
                self.inputs[nm][:self.batch_size]).nbytes) for nm in names}
        for nm in names:
            cuda_memcpy_h2d(self.dptrs[nm], self.inputs[nm][self.idx:end])
        self.idx = end
        return [int(self.dptrs[nm]) for nm in names]

    def read_calibration_cache(self):
        if self.cache_file.exists():
            return self.cache_file.read_bytes()

    def write_calibration_cache(self, cache):
        self.cache_file.write_bytes(bytes(cache))


TRT_TO_NP = {trt.float32: np.float32, trt.float16: np.float16,
             trt.int32: np.int32, trt.int64: np.int64, trt.bool: np.bool_}


def build_engine(onnx_path, engine_path, input_arrays, cache_file,
                 batch_size, workspace_gb=4.0, max_batch=8):
    builder = trt.Builder(TRT_LOGGER)
    network = builder.create_network(0)  # TRT 10: explicit-batch is the default
    parser = trt.OnnxParser(network, TRT_LOGGER)
    with open(onnx_path, "rb") as f:
        if not parser.parse(f.read()):
            for i in range(parser.num_errors):
                print("  ONNX parse error:", parser.get_error(i))
            raise RuntimeError(f"failed to parse {onnx_path}")

    # cast calib data to the PARSED network's input dtypes (handles the int64
    # timestep: if TRT keeps it int64 we feed int64, if it casts to int32 we feed int32)
    cast_inputs = {}
    for i in range(network.num_inputs):
        inp = network.get_input(i)
        np_dtype = TRT_TO_NP.get(inp.dtype, np.float32)
        cast_inputs[inp.name] = np.asarray(input_arrays[inp.name], dtype=np_dtype)
        print(f"  input {inp.name}: shape={list(inp.shape)} dtype={inp.dtype}")

    calibrator = Calibrator(cast_inputs, batch_size, cache_file)

    config = builder.create_builder_config()
    config.set_memory_pool_limit(trt.MemoryPoolType.WORKSPACE, int(workspace_gb * (1 << 30)))
    config.set_flag(trt.BuilderFlag.INT8)
    config.int8_calibrator = calibrator

    profile = builder.create_optimization_profile()
    for i in range(network.num_inputs):
        inp = network.get_input(i)
        shape = list(inp.shape)
        if any(d == -1 for d in shape):
            mn = [1 if d == -1 else d for d in shape]
            op = [1 if d == -1 else d for d in shape]
            mx = [max_batch if d == -1 else d for d in shape]
            profile.set_shape(inp.name, mn, op, mx)
    config.add_optimization_profile(profile)

    serialized = builder.build_serialized_network(network, config)
    if serialized is None:
        raise RuntimeError(f"engine build failed for {onnx_path}")
    engine_path.parent.mkdir(parents=True, exist_ok=True)
    with open(engine_path, "wb") as f:
        f.write(serialized)
    print(f"  built {engine_path.name}  INT8  {serialized.nbytes/1e6:.1f} MB")
    return engine_path


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--onnx_dir", default="onnx_fp32")
    ap.add_argument("--calib_dir", default="calib_data")
    ap.add_argument("--out_dir", default="engines")
    ap.add_argument("--batch_size", type=int, default=1)
    ap.add_argument("--which", default="both")  # encoder | unet | both
    args = ap.parse_args()

    onnx_dir = pathlib.Path(args.onnx_dir)
    calib = pathlib.Path(args.calib_dir)
    out = pathlib.Path(args.out_dir)

    if args.which in ("encoder", "both"):
        enc_inputs = {"image": np.load(calib / "enc_image.npy"),
                      "agent_pos": np.load(calib / "enc_agentpos.npy")}
        build_engine(onnx_dir / "obs_encoder.onnx", out / "obs_encoder_int8.engine",
                     enc_inputs, out / "obs_encoder_int8.cache", args.batch_size)
    if args.which in ("unet", "both"):
        unet_inputs = {"sample": np.load(calib / "unet_sample.npy"),
                       "timestep": np.load(calib / "unet_timestep.npy"),
                       "global_cond": np.load(calib / "unet_globalcond.npy")}
        build_engine(onnx_dir / "unet.onnx", out / "unet_int8.engine",
                     unet_inputs, out / "unet_int8.cache", args.batch_size)
    print("INT8 native-calibration build done")


if __name__ == "__main__":
    main()
